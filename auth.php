// 1. إدارة جلسات المستخدمين (Session Management)
// ==============================================================================

// التحقق من حالة الجلسة وإذا لم تكن قد بدأت بالفعل يتم البدء فيها لتجنب التحذيرات
if (session_status() === PHP_SESSION_NONE) {
    session_start(); // بدء الجلسة لتتمكن الصفحة من الوصول لبيانات المستخدم المسجل
}

// استدعاء ملف الاتصال بقاعدة البيانات لضمان توفر كائن الاتصال $pdo في جميع الصفحات التي تعتمد على auth.php
require_once 'db.php';

// ==============================================================================
// 2. التحقق من أمان تسجيل الدخول والصلاحية
// ==============================================================================

// التحقق مما إذا كان اسم المستخدم والدور مخزنين في الجلسة أم لا
if (!isset($_SESSION['role']) || !isset($_SESSION['userid'])) {
    // إذا لم يكن المستخدم مسجل دخوله، يتم إعادة توجيهه تلقائياً إلى صفحة تسجيل الدخول لحماية النظام
    header("Location: login.php");
    exit; // إيقاف تنفيذ بقية أسطر السكريبت فوراً بعد إعادة التوجيه لضمان عدم تسريب أي بيانات
}

// ==============================================================================
// 3. دالة التحقق من الصلاحيات المخصصة (Role Checking Helper)
// ==============================================================================

/**
 * دالة مساعدة للتحقق مما إذا كان المستخدم يملك صلاحية معينة أم لا
 * @param array|string $allowed_roles الصلاحية أو مصفوفة الصلاحيات المسموح لها بالدخول
 * @return bool true إذا كان المستخدم يمتلك الصلاحية، و false إذا لم يملكها
 */
function checkRole($allowed_roles) {
    // إذا تم تمرير الصلاحية كنص عادي يتم تحويله لمصفوفة
    if (!is_array($allowed_roles)) {
        $allowed_roles = [$allowed_roles]; // تحويل النص لمصفوفة تحتوي عنصراً واحداً
    }
    
    // التحقق من وجود دور المستخدم الحالي ضمن الدور المسموح به
    return in_array($_SESSION['role'], $allowed_roles, true); // إرجاع النتيجة
}
