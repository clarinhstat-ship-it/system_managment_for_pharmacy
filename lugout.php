<?php
// ==============================================================================
// 1. بدء الجلسة وتجهيز عملية تسجيل الخروج
// ==============================================================================

// فحص الجلسة وبدئها إذا لم تكن نشطة لتنظيف بيانات المستخدم
if (session_status() === PHP_SESSION_NONE) {
    session_start(); // بدء الجلسة
}

// استدعاء ملف قاعدة البيانات لتدوين الخروج في سجل الأمان إن وجد
require_once 'db.php';

// تدوين عملية تسجيل الخروج في سجل النشاطات والأمان
if (isset($_SESSION['name'])) {
    try {
        $logStmt = $pdo->prepare("INSERT INTO audit_logs (user_name, action, details) VALUES (:uname, 'تسجيل خروج', 'قام المستخدم بتسجيل الخروج من النظام')");
        $logStmt->execute([':uname' => $_SESSION['name']]);
    } catch (Exception $e) {
        // تجنب إيقاف الخروج عند حدوث خطأ بالسجل
    }
}

// ==============================================================================
// 2. تنظيف وإلغاء جميع متغيرات الجلسة وتدميرها
// ==============================================================================

$_SESSION = array(); // تفريغ مصفوفة الجلسة تماماً

// تدمير الكوكي الخاص بالجلسة في المتصفح للحماية التامة
if (ini_get("session.use_cookies")) {
    $params = session_get_cookie_params();
    setcookie(session_name(), '', time() - 42000,
        $params["path"], $params["domain"],
        $params["secure"], $params["httponly"]
    );
}

// تدمير الجلسة نهائياً من خادم PHP
session_destroy();

// ==============================================================================
// 3. إعادة التوجيه لصفحة تسجيل الدخول
// ==============================================================================

header("Location: login.php"); // التوجيه لصفحة الدخول
exit; // إيقاف تنفيذ السكريبت
?>